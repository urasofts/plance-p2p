  <h1>Place to Pay API Explorer</h1>
  <p>
    Explora y simula flujos de pago en ambiente de pruebas. Esta guía te ayuda a
    entender qué hace cada servicio y cómo empezar rápidamente.
  </p>
  <p>
    Este API Explorer está pensado para todo tipo de personas, no solo para
    perfiles técnicos. Fue diseñado para que cualquier usuario pueda comprender,
    paso a paso, cómo funciona una integración de pagos, incluso si no tiene
    experiencia previa en APIs, programación o arquitectura de software.
  </p>
  <p>
    En otras palabras: no necesitas ser experto. Si quieres aprender qué envía
    una solicitud, qué responde el sistema y cómo interpretar cada resultado,
    esta guía te acompaña de forma visual y práctica.
  </p>
  <p>
    Ahora Selecciona el tipo de servicio que quieras probar. Al hacer clic en una de las siguientes opciones,
    encontraras todos los tipos a probar dependiendo de tu selección.
  </p>
  <ol>
    <li>Si necesitas probar un pago con Web Checkout, selecciona la opción "Crear sesión".</li>
    <li>Si necesitas probar el proceso de un pago, selecciona la opción "Procesar pagos".</li>
    <li>Si necesitas probar el generar links de pago, selecciona la opción "Generar links".</li>
    <li>Si necesitas simular errores de algún tipo de sesión, selecciona la opción "Simular errores".</li>
  </ol>

