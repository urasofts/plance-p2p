  <h1>Generar links de pago</h1>

  <p>
    Este flujo te permite crear un <strong>link de cobro</strong> para
    compartirlo por canales externos como correo, WhatsApp, SMS o redes
    sociales, sin necesidad de integrar un checkout completo en tu sitio.
  </p>

  <p>
    Es una opción muy útil para ventas asistidas, cobros remotos, recaudo rápido
    y escenarios donde el comprador completa el pago desde un enlace seguro.
  </p>

  <h3>¿Cuándo usar Links de Pago?</h3>
  <ul>
    <li>
      Cuando solo quieres cobrar, sin tener que crear toda una página de pago
      con carrito, diseños y programación. Es como pedir una máquina para cobrar
      con tarjeta, pero versión digital.
    </li>
    <li>
      Cuando operas ventas por canales conversacionales o externos. No necesitas
      que pasen por un sitio web; tú les envías un link para pagar y listo, como
      cuando mandas un comprobante de pago.
    </li>
    <li>
      Cuando quieres acelerar habilitación comercial con bajo esfuerzo técnico.
      Perfecto si no tienes programadores ni tiempo para aprender cosas
      complicadas.
    </li>
  </ul>

  <h3>Qué podrás validar en esta vista</h3>
  <ul>
    <li>Generación del request para crear el link.</li>
    <li>Parámetros principales del cobro y su consistencia.</li>
    <li>Respuesta esperada del servicio y su interpretación funcional.</li>
  </ul>

  <h3>Flujo resumido</h3>
  <ol>
    <li>Configuras los datos del cobro.</li>
    <li>Generas el link desde el servicio.</li>
    <li>Compartes el enlace con el cliente.</li>
    <li>Monitoreas el resultado de la transacción.</li>
  </ol>

